export const IMAGE = 'ghcr.io/xuerns/pulsewatch:latest';

export function generateEnv(c) {
  const origin = `http://localhost:${c.port}`;
  return `# Generated by PulseWatch CLI
APP_ENV=production
APP_MODE=selfhosted
PUBLIC_APP_MODE=selfhosted
PORT=8080

# Security
JWT_SECRET=${c.jwtSecret}
JWT_ACCESS_EXPIRY=15m
JWT_REFRESH_EXPIRY=168h

# PostgreSQL
POSTGRES_USER=pulsewatch
POSTGRES_PASSWORD=${c.dbPassword}
POSTGRES_DB=pulsewatch
DB_HOST=postgres
DB_PORT=5432
DB_USER=pulsewatch
DB_PASSWORD=${c.dbPassword}
DB_NAME=pulsewatch
DB_SSLMODE=disable

# Redis
REDIS_HOST=redis
REDIS_PORT=6379
REDIS_PASSWORD=${c.redisPassword}

# Host port exposed by Docker (used by docker-compose.yml)
HOST_PORT=${c.port}

# CORS / Client
ALLOWED_ORIGIN=${origin}
PUBLIC_API_URL=${origin}/api/v1

# Self-hosted limits (0 = unlimited)
RECENT_CHECKS_LIMIT=60
SELFHOSTED_MAX_MONITORS=0
SELFHOSTED_MAX_ORGS=0
SELFHOSTED_MAX_MEMBERS=0
SELFHOSTED_MAX_PIC=10
SELFHOSTED_MIN_INTERVAL=10
SELFHOSTED_MAX_TIMEOUT=60

# SMTP (optional)
SMTP_HOST=
SMTP_PORT=587
SMTP_EMAIL=
SMTP_PASSWORD=
`;
}

export function generateCompose() {
  return `# Generated by PulseWatch CLI
services:
  postgres:
    image: postgres:16-alpine
    container_name: pulsewatch_postgres
    restart: unless-stopped
    environment:
      POSTGRES_USER: \${POSTGRES_USER}
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
      POSTGRES_DB: \${POSTGRES_DB}
    volumes:
      - postgres_data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \${POSTGRES_USER} -d \${POSTGRES_DB}"]
      interval: 10s
      timeout: 5s
      retries: 5
    networks:
      - pulsewatch_net

  redis:
    image: redis:7-alpine
    container_name: pulsewatch_redis
    restart: unless-stopped
    command: redis-server --requirepass \${REDIS_PASSWORD}
    volumes:
      - redis_data:/data
    healthcheck:
      test: ["CMD-SHELL", "redis-cli -a \${REDIS_PASSWORD} ping | grep PONG"]
      interval: 10s
      timeout: 5s
      retries: 5
    networks:
      - pulsewatch_net

  pulsewatch:
    image: ${IMAGE}
    container_name: pulsewatch_app
    restart: unless-stopped
    env_file:
      - .env
    ports:
      - "\${HOST_PORT:-8080}:8080"
    healthcheck:
      test: ["CMD-SHELL", "wget -q --spider http://127.0.0.1:8080/healthz || exit 1"]
      interval: 15s
      timeout: 5s
      retries: 3
      start_period: 10s
    depends_on:
      postgres:
        condition: service_healthy
      redis:
        condition: service_healthy
    networks:
      - pulsewatch_net

volumes:
  postgres_data:
  redis_data:

networks:
  pulsewatch_net:
    driver: bridge
`;
}
