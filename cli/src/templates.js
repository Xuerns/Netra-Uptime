export const IMAGE = 'ghcr.io/xuerns/netra-uptime:latest';

export function generateEnv(c) {
  const origin = `http://localhost:${c.port}`;
  return `# Generated by Netra Uptime CLI
APP_ENV=production
PORT=27346

# Security
JWT_SECRET=${c.jwtSecret}
JWT_ACCESS_EXPIRY=15m
JWT_REFRESH_EXPIRY=168h

# PostgreSQL
DB_DRIVER=postgres
POSTGRES_USER=netra
POSTGRES_PASSWORD=${c.dbPassword}
POSTGRES_DB=netra_uptime
DB_HOST=postgres
DB_PORT=5432
DB_USER=netra
DB_PASSWORD=${c.dbPassword}
DB_NAME=netra_uptime
DB_SSLMODE=disable

# Rate Limiter
AUTH_RATE_LIMIT=60

# Host port exposed by Docker (used by docker-compose.yml)
HOST_PORT=${c.port}

# CORS / Client
ALLOWED_ORIGIN=${origin}
PUBLIC_API_URL=${origin}/api/v1

# Self-hosted limits (0 = unlimited)
RECENT_CHECKS_LIMIT=60
SELFHOSTED_MAX_MONITORS=0
SELFHOSTED_MAX_ORGS=0
SELFHOSTED_MAX_MEMBERS=0
SELFHOSTED_MAX_PIC=10
SELFHOSTED_MIN_INTERVAL=10
SELFHOSTED_MAX_TIMEOUT=60

# SMTP (optional)
SMTP_HOST=
SMTP_PORT=587
SMTP_EMAIL=
SMTP_PASSWORD=
`;
}

export function generateCompose() {
  return `# Generated by Netra Uptime CLI
services:
  postgres:
    image: postgres:16-alpine
    container_name: netra_uptime_postgres
    restart: unless-stopped
    environment:
      POSTGRES_USER: \${POSTGRES_USER}
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
      POSTGRES_DB: \${POSTGRES_DB}
    volumes:
      - postgres_data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \${POSTGRES_USER} -d \${POSTGRES_DB}"]
      interval: 10s
      timeout: 5s
      retries: 5
    networks:
      - netra_uptime_net

  netra-uptime:
    image: ${IMAGE}
    container_name: netra_uptime_app
    restart: unless-stopped
    env_file:
      - .env
    ports:
      - "\${HOST_PORT:-27346}:27346"
    healthcheck:
      test: ["CMD-SHELL", "wget -q --spider http://127.0.0.1:27346/healthz || exit 1"]
      interval: 15s
      timeout: 5s
      retries: 3
      start_period: 10s
    depends_on:
      postgres:
        condition: service_healthy
    networks:
      - netra_uptime_net

volumes:
  postgres_data:

networks:
  netra_uptime_net:
    driver: bridge
`;
}
